"""Build the solution notebook from the lab notebook (on the `solution` branch).

Reads ../ECG_Preprocessing.ipynb, replaces every YOUR CODE placeholder with the solution line,
adds a banner cell, writes solution/ECG_Preprocessing_Solution.ipynb and, with --execute, runs
it in place with nbconvert from the repository root, so that code/ and data/ are found. The lab notebook is the only file edited by hand; rerun this script
after changing it. Each substitution must match exactly once, so a changed placeholder fails
loudly instead of leaving a blank in the solution.
"""
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LAB = ROOT / "ECG_Preprocessing.ipynb"
SOLUTION = ROOT / "solution" / "ECG_Preprocessing_Solution.ipynb"

# (placeholder variable, solution expression); matched on "<var> = None  # YOUR CODE ...".
FILLS = [
    # Task 2
    ("heart_rate_bpm", "60 / rr_s.mean()"),
    ("rr_ms", "1000 * rr_s"),
    ("sdrr_ms", "rr_ms.std(ddof=1)"),
    ("rmssd_ms", "np.sqrt(np.mean(np.diff(rr_ms) ** 2))"),
    # Task 3
    ("above", "signal > threshold"),
    ("starts", "np.flatnonzero(np.diff(np.r_[False, above, False].astype(int)) == 1)"),
    ("stops", "np.flatnonzero(np.diff(np.r_[False, above, False].astype(int)) == -1)"),
    ("beats", "np.array([a + np.argmax(signal[a:b]) for a, b in zip(starts, stops)], dtype=int)"),
    # Task 4A
    ("sos", 'butter(4, [low_hz, high_hz], btype="bandpass", fs=FS, output="sos")'),
    ("filtered", "sosfiltfilt(sos, x)"),
    # Task 4B
    ("d", "np.diff(x, prepend=x[0])"),
    ("width", "int(round(integration_s * FS)) + (1 - int(round(integration_s * FS)) % 2)"),
    ("averaged", 'np.convolve(d ** 2, np.ones(width) / width, mode="same")'),
    # Task 4C
    ("candidates", "highest_in_regions(score, starts, stops)"),
    ("strongest_first", "sorted(candidates, key=lambda p: -score[p])"),
    ("far_enough", "all(abs(peak - other) >= min_separation_s * FS for other in kept)"),
    # Task 4D
    ("median_rr", "np.median(np.diff(beats))"),
    ("too_close", "gap < correct_short * median_rr"),
    ("too_far", "gap > correct_long * median_rr"),
    ("k", "int(round(gap / median_rr))"),
    # Task 5
    ("scaler", "StandardScaler().fit(x_train)"),
    ("model", "RandomForestClassifier(n_estimators=100, random_state=42).fit(scaler.transform(x_train), y_train)"),
]
RETURN_FILLS = [("the predicted classes of x, scaled with the same scaler", "model.predict(scaler.transform(x))")]
# Task 1: each diagram starts one wave later than the previous letter of the cycle.
WAVE_ANSWERS = {1: "Q R S T P Q R S T P", 2: "R S T P Q R S T P Q", 3: "S T P Q R S T P Q R",
                4: "T P Q R S T P Q R S", 5: "P Q R S T P Q R S T"}

BANNER = ("# Solution notebook (branch `solution`)\n"
          "Generated from `../ECG_Preprocessing.ipynb` by `solution/build_solution.py`, which fills every "
          "**YOUR CODE** placeholder with the reference solution. Edit the lab notebook, then rebuild; "
          "do not edit this file by hand.\n")


def fill(source):
    text, count = source, 0
    for var, expr in FILLS:
        pattern = rf"^(\s*){re.escape(var)} = None\s+# YOUR CODE:.*$"
        text, n = re.subn(pattern, lambda m: f"{m.group(1)}{var} = {expr}  # Solution", text, flags=re.M)
        count += n
    for hint, expr in RETURN_FILLS:
        pattern = rf"^(\s*)return None\s+# YOUR CODE: {re.escape(hint)}.*$"
        text, n = re.subn(pattern, lambda m: f"{m.group(1)}return {expr}  # Solution", text, flags=re.M)
        count += n
    if "answers = {1: None, 2: None, 3: None, 4: None, 5: None}" in text:
        text = text.replace("answers = {1: None, 2: None, 3: None, 4: None, 5: None}",
                            "answers = " + json.dumps(WAVE_ANSWERS).replace('"1"', "1").replace('"2"', "2")
                            .replace('"3"', "3").replace('"4"', "4").replace('"5"', "5") + "  # Solution")
        count += 1
    return text, count


def build(execute=False):
    nb = json.loads(LAB.read_text())
    total = 0
    for cell in nb["cells"]:
        if cell["cell_type"] != "code":
            continue
        text, n = fill("".join(cell["source"]))
        total += n
        cell["source"] = text.splitlines(keepends=True)
        cell["outputs"], cell["execution_count"] = [], None
    expected = len(FILLS) + len(RETURN_FILLS) + 1
    if total != expected:
        raise SystemExit(f"{total} placeholders filled, expected {expected}: the lab notebook changed.")
    left = [l for c in nb["cells"] if c["cell_type"] == "code" for l in c["source"] if "= None  # YOUR CODE" in l]
    if left:
        raise SystemExit("Unfilled placeholders: " + "".join(left))
    first = "".join(nb["cells"][0]["source"])
    badge_lab = "blob/main/ECG_Preprocessing.ipynb"
    badge_sol = "blob/solution/solution/ECG_Preprocessing_Solution.ipynb"
    assert badge_lab in first, "Colab badge not found in the first cell"
    nb["cells"][0]["source"] = first.replace(badge_lab, badge_sol).splitlines(keepends=True)
    setup = "".join(nb["cells"][2]["source"])
    anchor = "# On Colab the notebook opens alone"
    assert anchor in setup, "Setup cell anchor not found"
    setup = setup.replace(anchor, "# This solution notebook lives in solution/: work from the repository root.\n"
                                  "if not Path(\"code/shared_ecg.py\").exists() and Path(\"../code/shared_ecg.py\").exists():\n"
                                  "    import os; os.chdir(\"..\")\n" + anchor)
    setup = setup.replace('subprocess.run(["git", "clone", "--quiet", REPO_URL], check=True)',
                          'subprocess.run(["git", "clone", "--quiet", "--branch", "solution", REPO_URL], check=True)')
    nb["cells"][2]["source"] = setup.splitlines(keepends=True)
    nb["cells"].insert(0, {"cell_type": "markdown", "metadata": {}, "source": BANNER.splitlines(keepends=True)})
    SOLUTION.write_text(json.dumps(nb, indent=1, ensure_ascii=False) + "\n")
    print(f"{SOLUTION.name}: {total} placeholders filled")
    if execute:
        subprocess.run([sys.executable, "-m", "jupyter", "nbconvert", "--to", "notebook", "--execute",
                        "--inplace", "--ExecutePreprocessor.timeout=1800", str(SOLUTION)], check=True, cwd=ROOT)
        print("executed")


if __name__ == "__main__":
    build(execute="--execute" in sys.argv)
